import logging
import httpx
from app.tools.registry import tool_registry
from app.schemas.tool_schemas import VectorSearchToolSchema
from app.core.config import settings

logger = logging.getLogger(__name__)


@tool_registry.register(
    name="vector_search",
    description="Searches through project documentation and code snippets using semantic vector similarity.",
    args_schema=VectorSearchToolSchema
)
async def vector_search_tool(query: str, top_k: int = 3) -> str:
    """
    Takes a natural language query, generates an embedding using Ollama,
    and performs a semantic search against the local vector database.
    """
    try:
        # 1. Generate embedding for the query using Ollama's embedding model
        async with httpx.AsyncClient() as client:
            response = await client.post(
                f"{settings.OLLAMA_BASE_URL}/api/embeddings",
                json={
                    "model": "nomic-embed-text:latest",
                    "prompt": query
                },
                timeout=30.0
            )
            
            if response.status_code != 200:
                logger.error(f"Failed to generate embedding from Ollama: {response.text}")
                return f"Error: Failed to connect to local embedding model ({response.status_code})."
            
            data = response.json()
            query_embedding = data.get("embedding")
            
            if not query_embedding:
                return "Error: Ollama returned an empty embedding vector."

        # 2. Simulate vector similarity matching (In Sprint 3, we will plug this directly into PostgreSQL pgvector)
        # For now, we simulate returning relevant architectural chunks based on the query search
        logger.info(f"Successfully generated vector embedding for query: '{query}' (Dims: {len(query_embedding)})")

        # Mock retrieved documentation chunks (simulating pgvector cosine similarity search results)
        mock_kb = [
            {
                "source": "docs/architecture.md", 
                "content": "DevAgent Core uses a modular agent loop following the ReAct (Reasoning and Acting) framework, separating tool discovery from execution."
            },
            {
                "source": "docs/database.md", 
                "content": "PostgreSQL is configured with the pgvector extension to store 768-dimensional embeddings generated by nomic-embed-text."
            },
            {
                "source": "docs/security.md", 
                "content": "All tool inputs must be validated using Pydantic v2 schemas before execution to prevent malformed argument crashes."
            }
        ]

        # Format results for the agent
        result_str = f"Found {len(mock_kb)} relevant documentation snippet(s) for query: '{query}':\n\n"
        for idx, doc in enumerate(mock_kb[:top_k], 1):
            result_str += f"--- Result {idx} (Source: {doc['source']}) ---\n{doc['content']}\n\n"

        return result_str.strip()

    except Exception as e:
        logger.error(f"Vector search tool failed: {str(e)}")
        return f"Error executing vector search: {str(e)}"