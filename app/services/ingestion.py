import os
import logging
import httpx
from pathlib import Path
from sqlalchemy.ext.asyncio import AsyncSession
from app.core.database import SessionLocal
from app.models.embedding import DocumentEmbedding
from app.core.config import settings

logger = logging.getLogger(__name__)

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent


async def get_embedding_from_ollama(text: str) -> list[float]:
    """Helper function to call Ollama and convert text into a 768-dim vector."""
    async with httpx.AsyncClient() as client:
        response = await client.post(
            f"{settings.OLLAMA_BASE_URL}/api/embeddings",
            json={
                "model": "nomic-embed-text:latest",
                "prompt": text
            },
            timeout=30.0
        )
        if response.status_code != 200:
            raise RuntimeError(f"Ollama embedding failed: {response.text}")
        
        data = response.json()
        return data.get("embedding")


async def ingest_documents():
    """
    Reads markdown docs from the workspace, chunks them, generates vectors,
    and stores them in PostgreSQL using pgvector.
    """
    print("\nStarting document ingestion into pgvector...")
    
    # Create docs folder if it doesn't exist
    docs_dir = PROJECT_ROOT / "docs"
    docs_dir.mkdir(exist_ok=True)
    
    sample_docs = {
        "architecture.md": "DevAgent Core uses a modular agent loop following the ReAct (Reasoning and Acting) framework, separating tool discovery from execution for maximum reliability.",
        "database.md": "PostgreSQL is configured with the pgvector extension to store 768-dimensional embeddings generated by the nomic-embed-text model locally via Ollama.",
        "security.md": "All tool inputs must be validated using Pydantic v2 schemas before execution to prevent malformed argument crashes and path traversal attacks outside project root."
    }

    async with SessionLocal() as session:
        for filename, content in sample_docs.items():
            file_path = docs_dir / filename
            if not file_path.exists():
                file_path.write_text(content, encoding="utf-8")

            print(f"Processing document: {filename}...")
            
            # 1. Generate vector embedding via Ollama
            try:
                vector = await get_embedding_from_ollama(content)
            except Exception as e:
                logger.error(f"Failed to generate embedding for {filename}: {str(e)}")
                continue

            # 2. Save into PostgreSQL DocumentEmbedding table
            db_record = DocumentEmbedding(
                source=f"docs/{filename}",
                content=content,
                embedding=vector
            )
            session.add(db_record)
        
        await session.commit()
    print("Document ingestion completed successfully. Vectors are stored in PostgreSQL.\n")